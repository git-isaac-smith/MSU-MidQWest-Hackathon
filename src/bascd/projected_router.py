"""Exact ordinary matching with a bounded cache of projected syndromes."""

import numpy as np
import pymatching

from .css_routed import observable_detector_mask


_PACKED = dict(bit_packed_shots=True, bit_packed_predictions=True)
_HASH_SALTS = np.random.default_rng(56).integers(1, 2**63, size=9, dtype=np.uint64) | np.uint64(1)


def _fingerprint(packed: np.ndarray) -> np.ndarray:
    """Hash 8 to 64 packed bytes per shot, including any partial final word."""
    width = packed.shape[1]
    words = packed[:, :width // 8 * 8].view("<u8")
    tail = packed[:, -8:].view("<u8")[:, 0]
    result = tail * _HASH_SALTS[0]
    for column in range(words.shape[1] - int(width % 8 == 0)):
        result ^= words[:, column] * _HASH_SALTS[column + 1]
    result ^= result >> np.uint64(33)
    result *= np.uint64(0xff51afd7ed558ccd)
    return result ^ (result >> np.uint64(33))


class _OrdinaryCache:
    def __init__(self, matching, width, edges):
        edges.sort(key=lambda edge: edge[2]["error_probability"])
        single = np.zeros((len(edges), width), dtype=np.uint8)
        for index, (start, end, _) in enumerate(edges):
            single[index, start // 8] ^= 1 << (start % 8)
            if end is not None:
                single[index, end // 8] ^= 1 << (end % 8)

        first, second = np.triu_indices(len(single), k=1)
        candidates = np.concatenate((single[first] ^ single[second], single, np.zeros((1, width), dtype=np.uint8)))
        buckets = 1 << (4 * len(candidates)).bit_length()
        self.bucket_mask = np.uint64(buckets - 1)
        slots = _fingerprint(candidates) & self.bucket_mask
        winners = np.full(buckets, -1, dtype=np.int32)
        # Larger candidate indices favor the zero/single-edge signatures and
        # favor the more probable single edge when two candidates collide.
        np.maximum.at(winners, slots, np.arange(len(candidates), dtype=np.int32))
        occupied = np.flatnonzero(winners >= 0)
        self.keys = candidates[winners[occupied]]
        self.predictions = matching.decode_batch(self.keys, **_PACKED)
        self.entries = np.zeros(buckets, dtype=np.int32)
        self.entries[occupied] = np.arange(len(occupied), dtype=np.int32)

    def decode(self, packed: np.ndarray, matching) -> np.ndarray:
        indices = self.entries[_fingerprint(packed) & self.bucket_mask]
        misses = np.any(self.keys[indices] != packed, axis=1)
        prediction = self.predictions[indices]
        if np.any(misses):
            prediction[misses] = matching.decode_batch(packed[misses], **_PACKED)
        return prediction


class ProjectedOrdinary:
    """Match the observable-bearing graph components of a one-observable DEM.

    Cache the original matcher's predictions for a bounded set of signatures
    generated by zero, one, or two edges. The circuit and model are used only
    at construction. Cache misses use ordinary matching on the same projected
    detector record as cache hits, preserving the original matcher's tie order.
    """

    def __init__(self, circuit, model):
        if model.num_observables != 1 or circuit.num_observables != 1 or circuit.num_detectors != model.num_detectors:
            raise ValueError("expected a circuit and model with matching detector counts and one observable")
        self._matching = pymatching.Matching.from_detector_error_model(model)
        self.mask = observable_detector_mask(self._matching, model.num_detectors)
        self._cache = None
        if 8 <= len(self.mask) <= 64:
            relevant = np.unpackbits(self.mask, bitorder="little")
            edges = [edge for edge in self._matching.edges() if relevant[edge[0]]]
            probabilities = [edge[2]["error_probability"] for edge in edges]
            # Bound the table size and skip setup when the expected number of
            # active graph edges makes zero-to-two-edge shots uncommon.
            if 1 <= len(edges) <= 1024 and min(probabilities) >= 0 and sum(probabilities) <= 4:
                self._cache = _OrdinaryCache(self._matching, len(self.mask), edges)

    def decode_batch(self, packed: np.ndarray) -> np.ndarray:
        """Return one packed uint8 prediction byte per packed detector row."""
        if packed.ndim != 2 or packed.dtype != np.uint8 or packed.shape[1] != len(self.mask):
            raise ValueError("expected little-endian packed detector rows")
        projected = np.bitwise_and(packed, self.mask, order="C")
        # Small batches decode before the table lookup can amortize its cost.
        if self._cache is None or len(projected) < 128:
            return self._matching.decode_batch(projected, **_PACKED)
        return self._cache.decode(projected, self._matching)
